/**
 * آلونک — سرپناهِ ابتداییِ هر شخصیتِ تازه.
 *
 * ## چرا لازم است؟
 * پیش از این، بازیکنِ بدون خانه **نمی‌توانست استراحت کند**: `startRestAtHome`
 * صریحاً خطای «اول باید خانه‌ای بخری یا اجاره کنی» می‌داد. آن طراحی وقتی
 * بی‌خطر بود که فرسودگیِ طبیعی وجود نداشت؛ ولی حالا سلامت با گذرِ ساعت بازی
 * کم می‌شود و کار زیر ۱۱ واحد سلامت ممکن نیست. یعنی بازیکنِ تازه‌واردی که
 * موجودی‌اش به درمان کامل نمی‌رسد، هیچ راهی برای برگشتن نداشت — مرگ برایش
 * اجباری بود، نه انتخابِ بازیکن. آلونک همان دریچهٔ رایگان است.
 *
 * ## چرا به‌عنوان «ملک» ساخته نشد؟
 * اگر آلونک یک ردیفِ `Property` بود، خودکار در فهرست دارایی‌ها، فروش، اجاره،
 * مهاجرت و میراث ظاهر می‌شد و سه مشکل می‌ساخت:
 *   • فروشِ یک داراییِ رایگان = ساختنِ پول از هیچ؛
 *   • اجاره‌دادنش = درآمدِ بی‌زحمت برای هر شخصیتِ تازه؛
 *   • و ارزش‌زدایی از ارزان‌ترین خانهٔ واقعی.
 * پس آلونک **وضعیتِ مشتق** است، نه ردیفِ دیتابیس: «تا وقتی خانهٔ قابل‌استفاده
 * یا اجاره‌نامهٔ فعالی نداری، یک آلونک داری». هیچ چیزی برای فروش، انتقال یا
 * ارث‌گذاری وجود ندارد؛ دقیقاً همان‌طور که باید باشد.
 *
 * ## چرا از ارزان‌ترین خانهٔ واقعی ضعیف‌تر است؟
 * نرخِ استراحت با ضریبِ سطح ملک بالا می‌رود (`1 + (level-1) * 0.5`). آلونک
 * عمداً **زیرِ سطح ۱** نشسته: نصفِ خستگی و یک‌چهارمِ سلامتِ یک خانهٔ سطح ۱.
 * پس:
 *   • خستگی را می‌توان با آن رفع کرد (بازی قفل نمی‌شود)،
 *   • ولی سلامت فقط با آن به‌سختی برمی‌گردد (درمانگاه و خانهٔ واقعی جای
 *     خودشان را نگه می‌دارند).
 */

/** نام انسانیِ آلونک — همان چیزی که در پنل‌ها دیده می‌شود. */
export const STARTER_SHELTER_TITLE = 'آلونک'

/** ضریب ریکاوریِ خستگی در آلونک نسبت به یک خانهٔ سطح ۱. */
export const SHELTER_FATIGUE_MULTIPLIER = 0.5
/** ضریب ریکاوریِ سلامت در آلونک نسبت به یک خانهٔ سطح ۱. */
export const SHELTER_HEALTH_MULTIPLIER = 0.25

/**
 * سقفِ سلامت در آلونک عمداً همان سقفِ پایه است: آلونک هیچ مزیتِ سلامتیِ
 * ساختاری نمی‌دهد، فقط اجازهٔ استراحت می‌دهد.
 */
export const SHELTER_PROVIDES_HEALTH_CAP = false

export interface ShelterPolicy {
  /** آیا بازیکن به آلونک دسترسی دارد؟ (فقط وقتی خانهٔ قابل‌استفاده ندارد) */
  isShelter: boolean
  /** ضریبِ کلِ ریکاوری نسبت به یک خانهٔ سطح ۱. */
  multiplier: number
  /** توضیحِ کوتاه برای پنل — بدون اصطلاح فنی. */
  hint: string
}

/**
 * وضعیت پناهگاه بازیکن.
 *
 * @param hasUsableHome آیا ملکِ قابل‌سکونتِ خودش یا اجاره‌نامهٔ فعال دارد؟
 */
export function resolveShelter(hasUsableHome: boolean): ShelterPolicy {
  if (hasUsableHome) {
    return {
      isShelter: false,
      multiplier: 1,
      hint: ''
    }
  }
  return {
    isShelter: true,
    multiplier: SHELTER_FATIGUE_MULTIPLIER,
    hint:
      `${STARTER_SHELTER_TITLE} داری: رایگان، همیشگی و به دردِ استراحت می‌خورد — ` +
      'ولی خستگی را دو برابر کندتر و سلامت را چهار برابر کندتر از یک خانهٔ واقعی برمی‌گرداند.'
  }
}

/** نرخِ خستگی در آلونک، به ازای هر دقیقهٔ بازی (همان واحدِ بقیهٔ مسیرها). */
export function shelterFatigueRate(baseRatePerGameMinute: number): number {
  return baseRatePerGameMinute * SHELTER_FATIGUE_MULTIPLIER
}

/** نرخِ سلامت در آلونک، به ازای هر دقیقهٔ بازی. */
export function shelterHealthRate(baseRatePerGameMinute: number): number {
  return baseRatePerGameMinute * SHELTER_HEALTH_MULTIPLIER
}
