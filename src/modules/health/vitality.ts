/**
 * فرسودگیِ طبیعیِ بدن — تنها منبعِ کاهشِ سلامت که به دستِ بازیکن نیست.
 *
 * ## چرا این فایل لازم است؟
 * پیش از این، سلامت فقط با «کار» و «اضافه‌کاری» کم می‌شد و کفِ آن ۱ بود
 * (`MIN_HEALTH`). یعنی بازیکن می‌توانست بی‌نهایت کار کند، سلامت را روی ۱ نگه
 * دارد و هرگز نمیرد. نتیجه: سیستمِ مرگ و میراث فقط روی کاغذ وجود داشت و
 * پروندهٔ میراث — با همهٔ تست‌هایش — در بازی واقعی هرگز باز نمی‌شد.
 *
 * راه‌حل «حذفِ کفِ ۱» نیست: آن‌وقت کار می‌شد «دکمهٔ مرگ» و مرگ به یک عمل
 * واحد وابسته می‌شد. راه‌حل درست، یک **فرسودگیِ آرام و پیوسته بر پایهٔ ساعت
 * بازی** است که کنارِ کار می‌نشیند:
 *
 *   کار (سقفِ افت سریع، کفِ ۱)  +  فرسودگیِ زمان (پیوسته، بی‌کف)
 *   ─────────────────────────────────────────────────────────────
 *   افتِ خالصِ سلامت  →  زیرِ ۱۱ دیگر نمی‌توانی کار کنی  →  باید درمان کنی
 *
 * پس مرگ هرگز یک‌شبه و از یک اقدام نیست: ماه‌ها بازی زمان می‌برد، پیامِ
 * هشدار در دو آستانه می‌آید، و «استراحت» و «درمانگاه» هر دو جلوی آن را
 * می‌گیرند. تصمیمِ بازیکن (زمان و پولِ درمان) ریسک را واقعاً کم می‌کند.
 *
 * ## چرا «ماه بازی» واحد است؟
 * یک ماه بازی دقیقاً ۱ روز واقعی است (`REAL_MS_PER_GAME_MONTH = 86,400,000`)،
 * پس نرخِ «هر ماه بازی» برای بازیکن یعنی «هر روزِ واقعی». این تنها واحدی
 * است که هم به بازی معنا می‌دهد و هم برای انسان قابل‌شمارش است.
 *
 * ## چرا پله‌ای و نه نمایی؟
 * پله‌ها قابل‌تست و قابل‌توضیح‌اند. با یک تغییر کوچک در ضریبِ نمایی، توازنِ
 * کلِ بازی به هم می‌ریخت؛ پله‌ها فقط یک عددِ خوانا را عوض می‌کنند.
 */

import { REAL_MS_PER_GAME_MONTH } from '../../utils/game-time'

/** آستانهٔ هشدارِ «سلامتت نصف شده» — تصمیمِ مالی را زودتر از بحران می‌طلبد. */
export const VITALITY_WARNING_HEALTH = 50
/** آستانهٔ هشدارِ بحرانی. */
export const VITALITY_CRITICAL_HEALTH = 20

/**
 * ضریبِ فرسودگی در حال استراحت.
 *
 * استراحت بدن را بازمی‌گرداند، پس بدنِ در حالِ استراحت کندتر فرسوده می‌شود —
 * ولی **صفر نمی‌شود**. اگر صفر می‌شد، بازیکن می‌توانست «شروع استراحت» را برای
 * همیشه باز بگذارد و نه بمیرد و نه استراحتِ تمام‌شده‌ای بگیرد؛ یعنی با یک
 * حالتِ بی‌فایده، کلِ مکانیزم را دور بزند.
 */
export const VITALITY_REST_FACTOR = 0.5

/**
 * پله‌های فرسودگی، به‌ازای هر **ماه بازی** (= ۱ روز واقعی).
 *
 * ستون آخر: با این نرخ، چقدر طول می‌کشد تا سلامت از ۱۰۰ به صفر برسد —
 * یعنی «اگر بازیکن کاملاً رها کند، چند روزِ واقعی بعد می‌میرد».
 *
 * جوانی عمداً ارزان است تا تازه‌وارد با یک هفته غیبت نمیرد؛ پیری عمداً سنگین
 * است تا سن — که تا امروز فقط «درِ شغل‌ها» را باز می‌کرد — بالاخره هزینهٔ
 * واقعی داشته باشد و «میراث» معنای تحت‌اللفظی بگیرد.
 */
const DECAY_STEPS: readonly { maxAge: number; perGameMonth: number }[] = [
  { maxAge: 30, perGameMonth: 2 }, //  ~۵۰ روز واقعی تا فوت
  { maxAge: 45, perGameMonth: 3 }, //  ~۳۳ روز
  { maxAge: 60, perGameMonth: 5 }, //  ~۲۰ روز
  { maxAge: 75, perGameMonth: 8 }, //  ~۱۲ روز
  { maxAge: Number.POSITIVE_INFINITY, perGameMonth: 12 } //  ~۸ روز
]

/** کمترین و بیشترین نرخِ ممکن — برای اعتبارسنجی و نمایش در پنل. */
export const MIN_DECAY_PER_GAME_MONTH = 2
export const MAX_DECAY_PER_GAME_MONTH = 12

/**
 * نرخِ فرسودگی بازیکن بر اساس سن.
 *
 * سنِ نامعتبر «جوان‌ترین پله» می‌گیرد، نه سنگین‌ترین: یک دادهٔ خراب نباید
 * بی‌صدا بازیکن را بکشد.
 */
export function vitalityDecayPerGameMonth(age: number): number {
  const years = Number.isFinite(age) ? Math.max(0, Math.floor(age)) : 0
  for (const step of DECAY_STEPS) {
    if (years < step.maxAge) {
      return step.perGameMonth
    }
  }
  return MAX_DECAY_PER_GAME_MONTH
}

/**
 * فرسودگیِ یک بازهٔ زمانی، بر حسب «واحدِ سلامت».
 *
 * خروجی عدد اعشاری است و عمداً رُند نمی‌شود: مصرف‌کننده باید فقط بخشِ صحیح
 * را کم کند و باقی‌ماندهٔ کسری را (با جابه‌جایی دقیق مبدأ زمان) به دورهٔ بعد
 * بسپارد. اگر همین‌جا گرد می‌شد، هر بار یک کسر کوچک گم می‌شد و فرسودگی
 * واقعی همیشه از فرسودگیِ اعلام‌شده کمتر می‌ماند.
 *
 * @param elapsedMs زمانِ سپری‌شده بر حسب میلی‌ثانیهٔ واقعی
 * @param perGameMonth نرخِ فرسودگی (خروجی `vitalityDecayPerGameMonth`)
 * @param resting آیا بازیکن در این بازه در حال استراحت بود؟
 */
export function vitalityDecayAmount(
  elapsedMs: number,
  perGameMonth: number,
  resting = false
): number {
  const ms = Number.isFinite(elapsedMs) ? Math.max(0, elapsedMs) : 0
  const rate = Number.isFinite(perGameMonth) ? Math.max(0, perGameMonth) : 0
  const factor = resting ? VITALITY_REST_FACTOR : 1
  return (ms / REAL_MS_PER_GAME_MONTH) * rate * factor
}

/**
 * جملهٔ انسانیِ نرخِ فرسودگی برای پنل سلامت.
 *
 * بازیکن باید بتواند **همین امروز** بفهمد بدنش با چه سرعتی فرسوده می‌شود؛
 * وگرنه کاهشِ بی‌دلیلِ سلامت به یک «باگ» شبیه است، نه به یک قانونِ بازی.
 */
export function vitalityRateHint(age: number): string {
  const rate = vitalityDecayPerGameMonth(age)
  if (rate <= MIN_DECAY_PER_GAME_MONTH) {
    return 'بدنت هنوز جوان است؛ فرسودگیِ روزانه‌ات در کمترین حد است.'
  }
  if (rate <= 3) return 'فرسودگیِ روزانه‌ات آرام است؛ با درمانِ به‌موقع بی‌خطر می‌ماند.'
  if (rate <= 5) return 'سن که بالا می‌رود، بدن زودتر فرسوده می‌شود؛ سلامتت را مرتب چک کن.'
  if (rate <= 8) return 'بدنت حالا با سرعتِ محسوسی فرسوده می‌شود؛ درمان را عقب نینداز.'
  return 'فرسودگیِ بدنت تند است؛ بدون درمانِ منظم، ادامهٔ زندگی ممکن نیست.'
}
