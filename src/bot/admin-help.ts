export function renderAdminHelpPage(index: number): string {
  const page = ADMIN_HELP_PAGES[Math.min(Math.max(index, 0), ADMIN_HELP_PAGES.length - 1)]!
  return [`*🛡️ ${page.title}*`, '', ...page.lines].join('\n')
}

/**
 * نکتهٔ یک‌بارهٔ راه‌اندازی منطقه، برای چت خصوصیِ کسی که گروه را ثبت کرده است.
 *
 * چرا این‌جا و نه در متنِ بازیکن؟ پیکربندی ربات کارِ اپراتور است و تنها او
 * دسترسی BotFather را دارد؛ چتِ گروهی جای این دانش نیست.
 */
export function groupSetupNote(): string {
  return panel({
    icon: '🛠️',
    title: 'یک نکتهٔ یک‌بارهٔ راه‌اندازی',
    sections: [
      {
        lines: [
          'اگر ربات در گروه به کلمه‌ها جواب نداد، تلگرام پیام‌های متنی گروه را به او نمی‌سپارد.',
          '',
          'در BotFather:',
          '`/mybots` → ربات → Bot Settings → Group Privacy → Turn off',
          '',
          'همین یک تنظیم است؛ بقیهٔ اعضای گروه کاری لازم نیست انجام دهند.'
        ]
      }
    ]
  })
}

export function adminHelpKeyboard(index: number): InlineKeyboard {
  const keyboard = new InlineKeyboard()
  if (index > 0) keyboard.text('⬅️ قبلی', `adm:help:${index - 1}`)
  keyboard.text(`${index + 1} / ${ADMIN_HELP_PAGES.length}`, `adm:help:${index}`)
  if (index + 1 < ADMIN_HELP_PAGES.length) keyboard.text('بعدی ➡️', `adm:help:${index + 1}`)
  keyboard.row().text('🏠 داشبورد', 'adm:home').text('بستن', 'panel:close')
  return keyboard
}
