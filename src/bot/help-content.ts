export function getHelpTopic(key: string): HelpTopic | undefined {
  return HELP_TOPICS.find((topic) => topic.key === key)
}

export function getHelpCategory(key: string): HelpCategory | undefined {
  return HELP_CATEGORIES.find((category) => category.key === key)
}

/** موضوع‌های یک فصل به همان ترتیبی که در فصل تعریف شده‌اند. */
export function getCategoryTopics(key: string): HelpTopic[] {
  const category = getHelpCategory(key)
  if (!category) {
    return []
  }
  return category.topicKeys
    .map((topicKey) => getHelpTopic(topicKey))
    .filter((topic): topic is HelpTopic => topic !== undefined)
}

/** متن پنل یک فصل: عنوان، توضیح کوتاه و فهرست موضوع‌ها. */
export function renderCategoryPanel(key: string): string {
  const category = getHelpCategory(key)
  if (!category) {
    return HELP_MAIN_TEXT
  }
  const topics = getCategoryTopics(key)
  return [
    `*${category.title}*`,
    '',
    category.description,
    '',
    ...topics.map((topic) => `• ${topic.title.replace(/^\S+\s/, '')}`),
    '',
    '👇 موضوع موردنظر را انتخاب کن.'
  ].join('\n')
}
