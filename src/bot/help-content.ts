/**
 * یک خط فهرست کلمه‌ها: خودِ کلمه، و *کاربرد* آن بخش.
 *
 * خط از کاتالوگ مرکزی ساخته می‌شود، نه دست‌نویس؛ پس راهنما نمی‌تواند کلمه‌ای
 * را معرفی کند که در بازی وجود ندارد و قالب «کلمه = کلمه» هم ممکن نیست.
 */
function commandLine(entry: CatalogEntry): string {
  const icon = SECTION_ICONS[entry.section] ?? '🔹'
  const purpose = SECTION_PURPOSE[entry.section] ?? entry.title
  return `${icon} «${entry.keyword}» — ${purpose}`
}

