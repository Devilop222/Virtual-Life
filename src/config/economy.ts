/**
 * ثابت‌های اقتصادی بازی در یک نقطه جمع شده‌اند تا توازن قابل بازبینی باشد.
 *
 * منطق پایه:
 *   دستمزد پاره‌وقت: ۳٬۰۰۰ تا ۷٬۵۰۰ تومان در دقیقه
 *   یک نشست ۳۰ دقیقه‌ای: ~۹۰٬۰۰۰ تا ~۲۲۵٬۰۰۰ تومان
 *   سرمایهٔ اولیه باید فقط هزینهٔ چند روز اول را پوشش دهد، نه بیشتر.
 */

/**
 * موجودی نقدی بازیکن در لحظهٔ ساخت شخصیت.
 *
 * معیار: حدود چهار نشست کاری با ارزان‌ترین شغل (۳٬۰۰۰ ت/دقیقه، ۳۰ دقیقه).
 * این مبلغ اجارهٔ ارزان‌ترین خانه (۱۵۰ هزار) و چند کالای فروشگاه را
 * پوشش می‌دهد، اما به خرید ملک یا شهریهٔ دانشگاه نمی‌رسد؛
 * پس شروع بازی بدون بن‌بست است و پیشرفت هم بی‌معنا نمی‌شود.
 */
export const STARTING_BALANCE = 400_000

/** پله‌های تجربه برای نمایش سطح مهارت بازیکن. */
const EXPERIENCE_TIERS: readonly { min: number; label: string }[] = [
  { min: 1_000, label: 'استاد' },
  { min: 400, label: 'ماهر' },
  { min: 150, label: 'نیمه‌ماهر' },
  { min: 50, label: 'کارآموز' },
  { min: 10, label: 'مبتدی' },
  { min: 0, label: 'تازه‌کار' }
]

/** برچسب فارسی سطح تجربه؛ برای بازیکن تازه «تازه‌کار» برمی‌گردد. */
export function experienceTierLabel(experience: number): string {
  const safe = Number.isFinite(experience) ? Math.max(0, experience) : 0
  return EXPERIENCE_TIERS.find((tier) => safe >= tier.min)?.label ?? 'تازه‌کار'
}

