/**
 * نرخ‌های مالیاتی بازی.
 *
 * مدل مالیاتی (عمداً ساده و بدون مالیات مضاعف):
 *   • مالیات بر درآمد حقوق — روی هر دستمزدی که بازیکن می‌گیرد (کار پاره‌وقت،
 *     اضافه‌کاری و حقوق کارمندی). ۵٪؛ آن‌قدر کم که یک بازیکن تازه‌وارد هم
 *     با ۹۰٬۰۰۰ تومان دستمزد فقط ۴٬۵۰۰ تومان بدهی مالیاتی بدهد.
 *   • مالیات بر سود کسب‌وکار — فقط زمانی گرفته می‌شود که سود از خزانه
 *     *بیرون* کشیده شود (برداشت مالک یا درآمد شعبه). چون حقوق کارمندان پیش از
 *     این مرحله از خزانه کسر شده، دستمزد دوباره مالیات نمی‌دهد؛ پس مالیات
 *     مضاعف رخ نمی‌دهد.
 *
 * همهٔ پولِ مالیات در `RegionStat.taxRevenue` منطقهٔ بازیکن ثبت می‌شود؛ یعنی
 * «مالیات محلی» روی پنل منطقه دیگر یک عدد ساختگی نیست، بلکه جمع واقعیِ
 * مالیاتِ کسرشده است.
 */
export const TAX_RATES = {
  /** مالیات بر درآمد حقوق (کار و اضافه‌کاری). */
  incomeTaxRate: 0.05,
  /** مالیات بر سود توزیع‌شدهٔ کسب‌وکار (برداشت مالک و درآمد شعبه). */
  businessProfitTaxRate: 0.15
} as const

