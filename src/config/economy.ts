/**
 * انتقالِ نقدی (جیب → جیب) و انتقالِ بانکی (حساب → حساب) دو مسیرِ جدا هستند.
 *
 * چرا سقفِ نقدی این‌قدر کوچک است؟ پولِ نقد همان چیزی است که بازیکن «در دست»
 * دارد: بدون ردِ سیستمی، بدون مالیات و بی‌نیاز از هر مجوز. اگر همان مسیر بتواند
 * میلیون‌ها جابه‌جا کند، سقفِ روزانهٔ امنتقالِ بانکی و مالیاتش فقط یک تشریفاتِ
 * دورزدنی می‌شوند. پس مبالغ بزرگ فقط از بانک می‌گذرند: آن‌جا سقفِ روزانه، مالیات
 * و ممیزی هست. این مرز عمدی است، نه تنبیهی.
 */
export const CASH_TRANSFER = {
  minAmount: 10_000,
  /** سقفِ *هر* انتقالِ نقدی (روزانه سقف ندارد). */
  maxAmount: 100_000
} as const

export const BANK_TRANSFER = {
  minAmount: 10_000,
  /**
   * پیشوندِ `reference` ردیفِ مالیاتِ انتقالِ بانکی.
   *
   * چرا یک نشانگر لازم است؟ موجودیِ فرستنده به اندازهٔ *ناخالص* کم می‌شود، ولی
   * دفتر کل دو ردیفِ واقعی می‌نویسد: خالص به گیرنده و مالیات به صندوق منطقه.
   * پس «چقدر امروز انتقال دادم» = جمعِ خالص + جمعِ مالیاتِ همان انتقال‌ها؛ و
   * تنها راهِ جداکردنِ این مالیات از مالیاتِ حقوق، همین نشانگر است. هر دو
   * (نویسنده و خواننده) از همین ثابت استفاده می‌کنند تا هرگز واگرا نشوند.
   */
  taxReference: 'مالیات انتقال بانکی',
  /**
   * سقفِ مجموعِ انتقال‌های بانکیِ *خروجی* یک بازیکن در یک روزِ بازی.
   * جمعی است، نه هر تراکنش: ۲۰ + ۲۰ + ۱۰ = ۵۰ و تراکنشِ بعدی رد می‌شود.
   */
  dailyOutgoingLimit: 50_000_000,
  /** مالیاتِ هر انتقالِ بانکی — به صندوق منطقهٔ فرستنده می‌رود. */
  taxRate: 0.001
} as const

/**
 * مالیاتِ یک انتقالِ بانکی (۰٫۱٪) — عدد صحیح و نامنفی.
 * از همان مبلغ مشمولِ بقیهٔ مالیات‌ها استفاده می‌کند تا سرریز و اعشارِ منفی نداشته باشیم.
 */
export function bankTransferTaxOf(amount: number): number {
  return Math.round(taxableAmount(amount) * BANK_TRANSFER.taxRate)
}

/** مبلغی که به حسابِ گیرنده می‌نشیند: ناخالص منهای مالیات. */
export function bankTransferNetOf(amount: number): number {
  return taxableAmount(amount) - bankTransferTaxOf(amount)
}

/** سقف ایمنی محاسبات مالیاتی — جلوی سرریز عدد را می‌گیرد. */
const MAX_TAXABLE_AMOUNT = Number.MAX_SAFE_INTEGER / 4

/** مبلغ مشمول مالیات: عدد صحیح و نامنفی و بدون سرریز. */
function taxableAmount(amount: number): number {
  if (!Number.isFinite(amount)) {
    return 0
  }
  const safe = Math.floor(amount)
  if (safe <= 0) {
    return 0
  }
  return Math.min(safe, MAX_TAXABLE_AMOUNT)
}

/** مالیات بر درآمد یک مبلغ ناخالص. */
export function incomeTaxOf(gross: number): number {
  return Math.round(taxableAmount(gross) * TAX_RATES.incomeTaxRate)
}

/** مالیات بر سود توزیع‌شدهٔ کسب‌وکار. */
export function businessProfitTaxOf(gross: number): number {
  return Math.round(taxableAmount(gross) * TAX_RATES.businessProfitTaxRate)
}

/** مبلغ خالص پس از کسر مالیات بر درآمد (هیچ‌وقت منفی نمی‌شود). */
export function netOfIncomeTax(gross: number): number {
  return taxableAmount(gross) - incomeTaxOf(gross)
}
