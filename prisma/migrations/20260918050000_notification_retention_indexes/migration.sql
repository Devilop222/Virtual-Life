-- ═══════════════════════════════════════════════════════════════════════════
-- ایندکس‌های اعلان — پیش‌نیازِ کارآمدیِ تخته و سیاست نگهداری.
--
-- `notifications` تنها جدولی بود که هیچ سقفِ رشد نداشت و فقط ایندکسِ `player_id`
-- و `status` داشت. نتیجه:
--   • «نشستنِ اعلان‌های یک بازیکن به ترتیب تازه‌ترین» مجبور بود همهٔ ردیف‌های او
--     را بخواند و مرتب کند،
--   • و هیچ پاکسازیِ دوره‌ای روی سنِ ردیف وجود نداشت، پس جدول بی‌نهایت رشد می‌کرد.
--
-- دو ایندکس زیر هر دو مشکل را می‌بندند:
--   • (player_id, created_at) → خواندنِ تخته هم‌ترتیب و ایندکس‌محور می‌شود.
--   • (status, created_at)    → فیلترِ نگهداری (وضعیت + سن) بدون Scan کل جدول.
--
-- مهاجرت افزودنی است؛ هیچ ستون/ردیفی تغییر نمی‌کند.
-- ═══════════════════════════════════════════════════════════════════════════

CREATE INDEX IF NOT EXISTS "notifications_player_id_created_at_idx"
  ON "notifications"("player_id", "created_at");

CREATE INDEX IF NOT EXISTS "notifications_status_created_at_idx"
  ON "notifications"("status", "created_at");
