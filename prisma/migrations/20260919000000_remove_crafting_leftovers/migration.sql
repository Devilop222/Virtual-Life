-- حذفِ کاملِ «کارگاه» — پاک‌سازیِ دادهٔ مردهٔ به‌جامانده.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- چرا این Migration لازم است؟
--
-- خروجی‌های کارگاه در زمان اجرا (در `CraftService.ensureOutputItemId`) به‌صورت
-- ردیفِ تازه در `shop_items` با کلیدهای `crafted_*` ساخته می‌شدند و اثری
-- نداشتند: `effects = {}`. پس از حذفِ خودِ قابلیت، این ردیف‌ها هیچ منبعی برای
-- تولید ندارند و هیچ مصرف‌کننده‌ای هم ندارند — نه در فروشگاه شهر عرضه می‌شوند،
-- نه Consumption/Use برایشان وجود دارد. ماندنشان فقط انبارِ بازیکن، فهرست
-- فروشگاه و بازار را آلوده می‌کند. پس پاک می‌شوند.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ارزیابیِ ایمنی (Impact Analysis)
--
--  • خروجی‌ها `effects = {}` داشتند: نه سلامت/خستگی/تجربه، نه بازیابی، نه
--    تجربه. یعنی هیچ داراییِ *قابل‌استفاده‌ای* حذف نمی‌شود.
--  • هیچ مسیرِ بازی این آیتم‌ها را مصرف نمی‌کند (مصرفِ کالا فقط از `effects`
--    می‌آید، که خالی است).
--  • هر دو کلیدِ خارجی به `shop_items` روی `ON DELETE CASCADE` هستند:
--    `player_inventory.item_id` و `market_listings.item_id`. پس حذفِ آیتم،
--    ردیف‌های انبار و آگهی‌های وابسته را هم پاک می‌کند. ترتیبِ زیر صریح نوشته
--    شده تا اثر، قابل‌خواندن و قابل‌ممیزی باشد — نه پنهان در Cascade.
--  • آگهیِ فعال روی یک آیتمِ بی‌اثر هم بی‌ارزش است؛ حذفش هیچ معاملهٔ واقعی‌ای
--    را از بین نمی‌برد (خریدارِ عاقل برای کالای بی‌اثر وجود ندارد).
--
-- ─────────────────────────────────────────────────────────────────────────────
-- چه چیزی *حذف نمی‌شود* (تاریخچه حفظ می‌شود)
--
--  • ردیف‌های دفتر کل با نوعِ `CRAFTING_FEE` — سندِ مالی‌اند و می‌مانند تا
--    ممیزیِ گذشته بازسازی‌شدنی باشد.
--  • رخدادهای `ITEM_CRAFTED` در `game_events` — سرگذشتِ بازیکن دست‌نخورده است.
--  • مقادیرِ enum `CRAFTING_FEE` / `ITEM_CRAFTED` — Postgres مقدارِ enum را
--    نمی‌اندازد و خواندنِ ردیف‌های تاریخی به آن‌ها نیاز دارد. عمداً باقی می‌مانند
--    و برچسب‌های فارسی‌شان در `ledger.service` / `event.service` حفظ شده است.
--
-- هیچ پولی جابه‌جا نمی‌شود: مقدارِ Swallowشده قبلاً در همان لحظهٔ ساخت واقعاً
-- خرج شده بود (Sink) و برگرداندنش یک MINT بی‌سند می‌ساخت.

-- ۱) آگهی‌های بازار روی آیتم‌های ساختهٔ کارگاه
--    (صریح، پیش از حذفِ آیتم — حتی با اینکه Cascade هم پاکشان می‌کند)
DELETE FROM "market_listings"
WHERE "item_id" IN (SELECT "id" FROM "shop_items" WHERE "key" LIKE 'crafted\_%');

-- ۲) ردیف‌های انبار بازیکنان
DELETE FROM "player_inventory"
WHERE "item_id" IN (SELECT "id" FROM "shop_items" WHERE "key" LIKE 'crafted\_%');

-- ۳) خودِ آیتم‌های کاتالوگ — بدون منبعِ تولید و بدون مصرف‌کننده
DELETE FROM "shop_items" WHERE "key" LIKE 'crafted\_%';
