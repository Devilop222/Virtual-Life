-- مهرِ تغییرِ سطحِ منطقه.
--
-- چرا لازم است؟ کلیدِ ضدتکرارِ خبرِ «سطح منطقه عوض شد» از *سطح مقصد* ساخته
-- می‌شد: `region-level:<group>:CITY`. آن کلید در `game_events.dedupe_key` و در
-- `notifications.dedupe_key` یکتاست و هرگز پاک نمی‌شود. پس منطقه‌ای که یک بار
-- «شهر» شده بود، اگر جمعیتش می‌افتاد و روستا می‌شد و دوباره از آستانه رد
-- می‌شد، برای بارِ دوم **هیچ خبر و هیچ اعلانی** نمی‌گرفت: یک تغییرِ واقعیِ سطح
-- بی‌صدا در دیتابیس گم می‌شد. سکوت در برابر یک تغییرِ واقعی، از پیامِ تکراری
-- بدتر است.
--
-- حالا هر تغییرِ *واقعی* سطح یک مهرِ زمانیِ خودش دارد و کلیدِ ضدتکرار همین مهر
-- را در خود می‌آورد. نتیجه:
--   • دو نویسندهٔ هم‌زمانِ یک تغییر → یک مقدار (نوشتارِ شرطیِ `updateMany`
--     تنها یک برنده دارد) → یک اعلان.
--   • تغییرِ بعدیِ همان منطقه → مهرِ تازه → اعلانِ تازه.
--
-- ستون NULL‌پذیر است: مناطقِ موجود «تاریخِ نامعلوم» دارند و مقدارِ ساختگی
-- (مثل now()) برایشان یک خبرِ دروغ می‌ساخت.
ALTER TABLE "groups" ADD COLUMN IF NOT EXISTS "level_changed_at" TIMESTAMP(3);
