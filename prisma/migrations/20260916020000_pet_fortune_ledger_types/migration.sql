-- پیش‌تر هر سه مسیر با نوعِ TRANSFER ثبت می‌شدند:
--  • سرپرستی حیوان و غذایش — کسرِ یک‌طرفه از کیف (BURN واقعی، سینکِ
--    هزینهٔ نگهداری) ولی به شکل «انتقالِ بدون مقصد»
--  • هدیهٔ روزانهٔ حیوان — واریزِ یک‌طرفه به کیف (MINT واقعی، مثل
--    REWARD_PAYOUT) ولی به شکل «انتقالِ بدون مبدأ»
--  • هزینهٔ پیش‌بینی‌نشدهٔ شانس روزانه — همان الگوی کسر یک‌طرفه
--
-- ممیزیِ عرضهٔ پول (money-supply) هر ردیف تک‌طرفه را با نوعش طبقه‌بندی
-- می‌کند: TRANSFERِ بدون طرفِ دوم یعنی «پولِ بی‌صاحب» (SHARED) و آشتیِ
-- دفتر کل را می‌شکند. با انواعِ صریح، SINK و MINT هر یک در ستونِ درستِ
-- گزارش می‌نشینند و هیچ ردیفِ تک‌طرفه‌ای TRANSFER خوانده نمی‌شود.
