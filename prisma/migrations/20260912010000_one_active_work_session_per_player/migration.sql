-- Integrity: هر بازیکن همزمان فقط یک نوبت کاریِ فعال (ACTIVE).
--
-- تا حالا «شیفت فعال نداشتن» فقط با read-then-create داخل یک تراکنش چک
-- می‌شد. در سطح جداسازی پیش‌فرض Postgres (READ COMMITTED) دو درخواست
-- همزمان (دابل‌کلیک روی «شروع کار»، یا دو دستگاه) هر دو هیچ نشستِ فعالی
-- نمی‌دیدند و هر دو نشست می‌ساختند. پیامدها:
--   • دو ظرفیتِ شغل اشغال می‌شد ولی فقط یکی آزاد می‌شد → ظرفیتِ شغل برای
--     همیشه یک واحد کمتر (نشتیِ دائمیِ job_capacities.occupied)
--   • «پایان کار» یکی از دو نشست را تسویه می‌کرد و دیگری ACTIVE می‌ماند،
--     پس بازیکن تا ابد «مشغول به کار» بود و شروع کارِ تازه برایش بسته
--   • تعریفِ اشتغال (employment.ts) و آمارِ «شاغلان» دو نشست را یک نفر
--     می‌شمردند و عدد درست بود، ولی ظرفیت و وضعیتِ بازیکن خراب می‌شد
--
-- الگو دقیقاً همان قیدی است که «یک قرارداد اجارهٔ فعال» و «یک وام فعال» و
-- «یک انتخاباتِ باز» را تضمین می‌کند.
-- ═══════════════════════════════════════════════════════════

-- ۱) پاکسازی نشست‌های تکراریِ ACTIVE از raceهای قدیمی.
--    قدیمی‌ترین نشست (اولویت با اولین کلیک) فعال می‌ماند تا همان یک شیفتِ
--    واقعیِ بازیکن تسویه شود؛ بقیه CANCELLED می‌شوند چون شیفتِ مستقلی
--    نبوده‌اند. ظرفیتِ آزادشده در اولین همگام‌سازیِ سرویس ظرفیت
--    (job-market.service → reconcileOccupied) با شمارش واقعی نشست‌های فعال
--    آشتی داده می‌شود، پس اینجا به job_capacities دست نمی‌زنیم.
UPDATE "work_sessions" a
SET "status" = 'CANCELLED',
    "ended_at" = COALESCE(a."ended_at", now())
FROM "work_sessions" b
WHERE a."player_id" = b."player_id"
  AND a."status" = 'ACTIVE' AND b."status" = 'ACTIVE'
  AND (b."started_at" < a."started_at"
       OR (b."started_at" = a."started_at" AND b."id" < a."id"));

-- ۲) قید اصلی: حداکثر یک نشست فعال برای هر بازیکن.
CREATE UNIQUE INDEX IF NOT EXISTS "one_active_work_session_per_player"
  ON "work_sessions"("player_id")
  WHERE "status" = 'ACTIVE';
