-- ═══════════════════════════════════════════════════════════
-- عمق خانواده: گرمای رابطه + قفل روزانهٔ فعالیت مشترک
--
-- چرا؟ زندگی مشترک پیش از این فقط «پاداش روزانه + طلاق» بود؛ هیچ وضعیت
-- زنده‌ای نداشت. حالا رابطه یک عدد «گرما/صمیمیت» دارد (در همان
-- `relationships.strength` نوع SPOUSE) که با بی‌توجهی کم می‌شود و با
-- فعالیت مشترک و هدیه زیاد. برای اینکه فرسایشِ گرما از «آخرین تعاملِ
-- واقعی» حساب شود نه از روز عقد، یک لنگر زمانی لازم است:
--   • `last_warmth_at` = آخرین لحظه‌ای که گرما لمس شد (عقد/پاداش/هدیه/فعالیت)
-- و برای اینکه «وقت مشترک» روزی بیش از یک‌بار خرج نشود:
--   • `last_activity_day_index` = شماره روزِ آخرین فعالیت مشترک
-- هر دو ستون برای ازدواج‌های قدیمی NULL است؛ سرویس‌ها مقدار تهی را
-- «از لحظهٔ عقد» و «هرگز انجام نشده» معنا می‌کنند.
-- ═══════════════════════════════════════════════════════════

ALTER TABLE "marriages" ADD COLUMN "last_activity_day_index" INTEGER;
ALTER TABLE "marriages" ADD COLUMN "last_warmth_at" TIMESTAMP(3);

-- ═══════════════════════════════════════════════════════════
-- دو نوع تراکنش جدید برای دفتر کلِ صادق
--
-- • FAMILY_EXPENSE: خرجِ مشترک خانواده (وقت مشترک) — پول از بازی خارج
--   می‌شود (Sink) و نباید در دفتر کل «برداشت» یا «خرید فروشگاه» دیده شود.
-- • SKILL_TRAINING: هزینهٔ تمرینِ فعالِ مهارت — این هم Sink است و پیش از
--   این با هیچ نوع دقیقی قابل ثبت نبود.
-- ═══════════════════════════════════════════════════════════

ALTER TYPE "TransactionType" ADD VALUE IF NOT EXISTS 'FAMILY_EXPENSE';
ALTER TYPE "TransactionType" ADD VALUE IF NOT EXISTS 'SKILL_TRAINING';
