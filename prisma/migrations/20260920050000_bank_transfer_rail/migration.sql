-- نوعِ تراکنشِ «انتقالِ بانکی».
--
-- چرا یک مقدارِ enum لازم است و نمیشود با `TRANSFER` سر کرد؟ سقفِ روزانهٔ
-- انتقالِ بانکی باید *جمعی* باشد (۲۰ + ۲۰ + ۱۰ = ۵۰)، و جمعِ روزانه فقط با
-- پرس‌وجوی ایندکس‌شده روی ردیف‌های دفتر کل ممکن است. اگر انتقالِ بانکی از
-- انتقالِ نقدی جدا نباشد، یا باید مرجع/رشته را پارس کنیم (شکننده) یا سقف را
-- روی همهٔ انتقال‌ها بگذاریم (آن‌وقت سقفِ کوچکِ نقدی بی‌معنا می‌شود). یک نوعِ
-- جدا هم جمعِ روزانه را ارزان می‌کند و هم ممیزیِ بعدی را.
--
-- مقدارِ `TRANSFER` دست‌نخورده می‌ماند: ردیف‌های موجودِ دیتابیس همان انتقالِ
-- نقدی (کیف پول به کیف پول) بودند و باید همان معنا را نگه دارند.
ALTER TYPE "TransactionType" ADD VALUE IF NOT EXISTS 'BANK_TRANSFER';

-- نمایهٔ جمعِ روزانهٔ فرستنده: پرس‌وجو همیشه «خروجی‌های یک بازیکن در یک بازهٔ
-- زمانی، از یک نوع» است، پس ترتیبِ همین سه ستون درست است. نام دقیقاً همان
-- چیزی است که Prisma از `@@index([sourcePlayerId, type, createdAt])` می‌سازد
-- تا اسکیما و دیتابیس از هم واگرا نشوند.
CREATE INDEX IF NOT EXISTS "financial_transactions_source_player_id_type_created_at_idx"
  ON "financial_transactions" ("source_player_id", "type", "created_at");
