import { readFileSync } from 'fs'

/**
 * خواندنِ متنِ سورس برای تست‌های «قراردادی».
 *
 * چرا این پوسته؟ چند تست، ترتیب یا شکلِ کد را با جست‌وجوی رشته‌ای در سورس
 * می‌سنجند و الگوهای چندخطی می‌نویسند (مثل `'if (x) {\n  return\n}'`). روی
 * چک‌اوتِ ویندوزی، Git پایانِ خطوط را به CRLF تبدیل می‌کند و همان الگو دیگر
 * پیدا نمی‌شود؛ نتیجه این بود که تست روی Linux سبز و روی ویندوز قرمز می‌شد و
 * بعضی سنجه‌ها بی‌سروصدا ضعیف می‌شدند (indexOf منفی → برشِ تقریباً کلِ فایل).
 *
 * پس همهٔ تست‌ها سورس را از همین‌جا می‌خوانند: یکدست‌سازی پایانِ خطوط، نه
 * تغییرِ خودِ فایل.
 */
export function readText(path: string): string {
  return readFileSync(path, 'utf8').replace(/\r\n?/g, '\n')
}
